function computeStatsForRole(ovr: number, pos: PositionCode): PlayerStats {
  if (pos === 'GK') {
    return {
      pac: ovr + 3,
      sho: ovr + 2,
      pas: ovr - 2,
      dri: ovr + 5,
      def: Math.max(82, ovr - 32),
      phy: ovr + 2,
    };
  }
  if (pos === 'ST' || pos === 'CF') {
    return {
      pac: ovr + 6,
      sho: ovr + 7,
      pas: ovr - 3,
      dri: ovr + 4,
      def: Math.max(58, ovr - 52),
      phy: ovr + 2,
    };
  }
  if (pos === 'LW' || pos === 'RW') {
    return {
      pac: ovr + 8,
      sho: ovr + 3,
      pas: ovr + 2,
      dri: ovr + 7,
      def: Math.max(58, ovr - 50),
      phy: ovr - 5,
    };
  }
  if (pos === 'CAM') {
    return {
      pac: ovr + 3,
      sho: ovr + 3,
      pas: ovr + 7,
      dri: ovr + 6,
      def: Math.max(70, ovr - 36),
      phy: ovr - 3,
    };
  }
  if (pos === 'CM') {
    return {
      pac: ovr + 1,
      sho: ovr + 1,
      pas: ovr + 7,
      dri: ovr + 5,
      def: ovr - 6,
      phy: ovr - 1,
    };
  }
  if (pos === 'CDM') {
    return {
      pac: ovr - 1,
      sho: ovr - 3,
      pas: ovr + 4,
      dri: ovr + 1,
      def: ovr + 6,
      phy: ovr + 5,
    };
  }
  if (pos === 'LB' || pos === 'RB') {
    return {
      pac: ovr + 7,
      sho: ovr - 12,
      pas: ovr + 2,
      dri: ovr + 3,
      def: ovr + 3,
      phy: ovr + 1,
    };
  }
  // CB
  return {
    pac: ovr + 1,
    sho: Math.max(72, ovr - 36),
    pas: ovr - 6,
    dri: ovr - 5,
    def: ovr + 7,
    phy: ovr + 6,
  };
}

function defaultTraitsForPos(pos: PositionCode): string[] {
  if (pos === 'GK') return ['Phản xạ xuất thần', 'Đối mặt 1vs1', 'Chống bóng bổng'];
  if (pos === 'ST' || pos === 'CF') return ['Dứt điểm 1 chạm', 'Tốc độ tia chớp', 'Sút xoáy'];
  if (pos === 'LW' || pos === 'RW') return ['Tốc độ tia chớp', 'Sút xoáy', 'Qua người'];
  if (pos === 'CAM' || pos === 'CM') return ['Kiến tạo vàng', 'Chuyền dài', 'Sút xa'];
  if (pos === 'CDM') return ['Siêu đánh chặn', 'Chuyền dài', 'Bền bỉ'];
  if (pos === 'LB' || pos === 'RB') return ['Tốc độ tia chớp', 'Tạt bóng sớm', 'Bền bỉ'];
  return ['Siêu đánh chặn', 'Đánh đầu mạnh', 'Xoạc bóng chuẩn'];
}

function computeBaseBpForOvr(season: SeasonCode, ovr: number): number {
  if (season === 'LE') {
    // OVR 135..140 -> 1,950B .. 7,520B BP
    return Math.round((1950 + Math.pow(Math.max(0, ovr - 135), 1.55) * 460) * 1_000_000_000);
  }
  if (season === '26UCL') {
    // OVR 120..128 -> 620B .. 2,350B BP
    return Math.round((620 + Math.pow(ovr - 120, 1.65) * 86) * 1_000_000_000);
  }
  if (season === '26TOTY') {
    return Math.round((510 + (ovr - 119) * 145) * 1_000_000_000);
  }
  if (season === '26TOTS') {
    return Math.round((430 + (ovr - 118) * 115) * 1_000_000_000);
  }
  if (season === '26VB') {
    return Math.round((260 + Math.pow(ovr - 110, 1.55) * 42) * 1_000_000_000);
  }
  if (season === 'BDO') {
    return Math.round((360 + (ovr - 116) * 95) * 1_000_000_000);
  }
  if (season === 'UP') {
    return Math.round((160 + (ovr - 114) * 52) * 1_000_000_000);
  }
  if (season === '25UCL') {
    return Math.round((190 + (ovr - 114) * 55) * 1_000_000_000);
  }
  return Math.round((85 + (ovr - 111) * 32) * 1_000_000_000);
}

interface CompactPlayerSeed {
  id: string;
  name: string;
  shortName: string;
  season: SeasonCode;
  seasonLabel: string;
  ovr: number;
  pos: PositionCode;
  nat: string;
  club: string;
  jersey: number;
  minifaceUrl: string;
  altMinifaceUrl?: string;
  salary?: number;
  pf?: number;
  wf?: number;
  sm?: number;
  traits?: string[];
}

function buildActiveTemplate(seed: CompactPlayerSeed): PlayerTemplate {
  const clubMeta = CLUB_LICENSE_REGISTRY[seed.club] ?? CLUB_LICENSE_REGISTRY.RMA;
  const salary =
    seed.salary ??
    (seed.season === 'LE'
      ? Math.min(36, Math.max(32, 32 + Math.floor((seed.ovr - 135) * 0.8)))
      : seed.season === 'UP'
      ? Math.min(26, Math.max(23, 23 + Math.floor((seed.ovr - 114) * 0.75)))
      : seed.season === '26UCL'
      ? Math.min(33, Math.max(28, 28 + Math.floor((seed.ovr - 120) * 0.65)))
      : Math.min(31, Math.max(25, 25 + Math.floor((seed.ovr - 111) * 0.55))));
  const fallbackSpec: PlayerMinifaceSpec = {
    skinHex: '#E0AC69',
    hairStyle: 'parted_classic',
    hairHex: '#18181B',
    facialHair: 'clean',
    kitPattern: 'collar_trim',
    kitPrimary: clubMeta.primaryHex,
    kitSecondary: clubMeta.secondaryHex,
    kitTrim: clubMeta.borderHex,
  };

  return {
    id: seed.id,
    name: seed.name,
    shortName: seed.shortName,
    season: seed.season,
    seasonLabel: seed.seasonLabel,
    baseOvr: seed.ovr,
    salary,
    preferredFoot: seed.pf ?? 5,
    weakFoot: seed.wf ?? (seed.pos === 'GK' || seed.pos === 'CB' ? 3 : 4),
    skillMoves:
      seed.sm ??
      (seed.pos === 'GK'
        ? 2
        : seed.pos === 'CB'
        ? 3
        : seed.pos === 'LW' || seed.pos === 'RW' || seed.pos === 'ST' || seed.pos === 'CAM'
        ? 5
        : 4),
    goldTraits: seed.traits ?? defaultTraitsForPos(seed.pos),
    position: seed.pos,
    nationalityCode: seed.nat,
    nationalityName: NATION_NAMES[seed.nat] ?? seed.nat,
    clubCode: seed.club,
    clubName: clubMeta.officialName,
    baseValueBp: computeBaseBpForOvr(seed.season, seed.ovr),
    jerseyNumber: seed.jersey,
    primaryColor: clubMeta.primaryHex,
    secondaryColor: clubMeta.secondaryHex,
    stats: computeStatsForRole(seed.ovr, seed.pos),
    minifaceUrl: seed.minifaceUrl,
    ...(seed.altMinifaceUrl ? { altMinifaceUrl: seed.altMinifaceUrl } : {}),
    miniface: fallbackSpec,
  };
}

